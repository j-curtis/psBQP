def get_initial_occupation_numbers(nambu_identity: jnp.ndarray, omega_grid: jnp.ndarray, temperature: float) -> jnp.ndarray:
    """A function returning the initial occupation numbers given temperature T. f function

    Args:
        nambu_identity (jnp.ndarray): Identity matrix in nambu space 
        omega_grid (jnp.ndarray): Grid of frequencies
        temperature (jnp.ndarray): System temperature

    Returns:
        jnp.ndarray: f distribution function defined on the meshgrid within nambu space
    """
    return nambu_identity*jnp.tanh(0.5*omega_grid/temperature)
